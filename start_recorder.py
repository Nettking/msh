"""Start the FCP MTConnect recorder, optionally as a headless Federation node.

The simplest first-run form is now::

    python start_recorder.py FCP1-...

The recorder creates/reuses its stable identity, joins the Federation, runs the
existing bounded private-network MTConnect scan, selects discovered sources on
first configuration, starts managed recording, and accepts later scan/source
changes from any trusted Federation member. Manual ``NAME=URL`` sources remain
available for explicit deployments.
"""

